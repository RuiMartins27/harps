# ============================================================
# Plot settings
# ============================================================

plt.rcParams.update({
    "font.family": "sans-serif",
    "font.size": 11,
    "axes.labelsize": 12,
    "axes.titlesize": 12,
    "legend.fontsize": 9,
})

# ============================================================
# Convert gas temperature to Kelvin
# ============================================================

for name, data in datasets.items():

    if data["Tg_unit"] == "eV":
        data["Tg_K"] = data["Tg"] * 11604.518

    elif data["Tg_unit"] == "K":
        data["Tg_K"] = data["Tg"]

    else:
        raise ValueError(f"Unknown Tg unit for {name}")
    
# ============================================================
# Create plots
# ============================================================

fig, axes = plt.subplots(3, 1, figsize=(7, 11), sharex=True)

for name, data in datasets.items():

    r = data["r"]
    ne = data["ne"]
    Te = data["Te"]
    Tg_K = data["Tg_K"]

    # Dense radial grid for interpolation
    r_interp = np.linspace(r.min(), r.max(), 1000)

    # Shape-preserving interpolation
    ne_interp = PchipInterpolator(r, ne)(r_interp)
    Te_interp = PchipInterpolator(r, Te)(r_interp)
    Tg_interp = PchipInterpolator(r, Tg_K)(r_interp)

    # -------------------------
    # Electron density
    # -------------------------
    axes[0].plot(
        r_interp * 1000,
        ne_interp / 1e18,
        label=name
    )

    axes[0].scatter(
        r * 1000,
        ne / 1e18,
        s=25
    )

    # -------------------------
    # Electron temperature
    # -------------------------
    axes[1].plot(
        r_interp * 1000,
        Te_interp,
        label=name
    )

    axes[1].scatter(
        r * 1000,
        Te,
        s=25
    )

    # -------------------------
    # Gas temperature
    # -------------------------
    axes[2].plot(
        r_interp * 1000,
        Tg_interp,
        label=name
    )

    axes[2].scatter(
        r * 1000,
        Tg_K,
        s=25
    )


# ============================================================
# Formatting
# ============================================================

axes[0].set_ylabel(r"$n_e$ [$10^{18}$ m$^{-3}$]")
axes[0].set_yscale("log")
axes[0].set_ylim(0.01, 350)
axes[0].grid(True, alpha=0.3)
axes[0].legend()

axes[1].set_ylabel(r"$T_e$ [eV]")
axes[1].grid(True, alpha=0.3)

axes[2].set_ylabel(r"$T_g$ [K]")
axes[2].set_xlabel("Radius [mm]")
